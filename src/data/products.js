// Best-by is 9:00 PM on the given day. After 9 PM, "today" rolls to tomorrow
// so the sample data never starts out already expired.
function bestByFor(daysFromToday) {
  const date = new Date();
  if (date.getHours() >= 21) date.setDate(date.getDate() + 1);
  date.setDate(date.getDate() + daysFromToday);
  date.setHours(21, 0, 0, 0);
  return date.toISOString();
}

const products = rawProducts.map(({ expiresInDays, ...product }) => ({
  ...product,
  bestBy: bestByFor(expiresInDays),
}));

export const productCategories = ["Meals", "Drinks", "Fruit", "Salads", "Snacks"];

export default products;
